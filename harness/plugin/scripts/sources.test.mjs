// node --test harness/plugin/scripts/sources.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { settings, lineProblems, sourceLine, check, verdict } from './sources.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const cfg = { sources: { product: { path: 'docs/product/', idPattern: 'REQ-\\d+' }, design: { path: 'docs/design/' } }, sourcesCheck: { code: ['src'], backlog: 'factory/sources-backlog.txt' } };

function project(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'factory-sources-'));
  const all = {
    'factory/harness.json': JSON.stringify(cfg),
    'docs/product/sign-in.md': '# Sign in\n\nREQ-1 A teacher signs in.\nREQ-2 A wrong password is refused.\n',
    'docs/design/sign-in.md': '# Sign in\n\n## Endpoints\n\n## Rules\n',
    ...files,
  };
  for (const [rel, text] of Object.entries(all)) { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), text); }
  return root;
}
const s = settings(cfg);

test('a Source line resolves: its file, its section and its requirement ids', () => {
  const root = project({});
  assert.deepEqual(lineProblems(root, '// Source: docs/design/sign-in.md § Endpoints; REQ-1, REQ-2', s), []);
  assert.deepEqual(lineProblems(root, '# Source: docs/design/missing.md; REQ-9', s), ['no such file: docs/design/missing.md', 'no such requirement: REQ-9']);
  assert.deepEqual(lineProblems(root, '-- Source: docs/design/sign-in.md § Jobs', s), ['no section "Jobs" in docs/design/sign-in.md']);
  assert.deepEqual(lineProblems(root, '// Source: the design', s), ['the Source line names no file and no requirement']);
  assert.equal(sourceLine('import x\n// Source: a.md\n'), '// Source: a.md');
});

test('every hand-written file needs a resolving line; a generated one is skipped', () => {
  const root = project({
    'src/good.js': '// Source: docs/design/sign-in.md § Rules; REQ-2\nexport const x = 1;\n',
    'src/none.js': 'export const y = 2;\n',
    'src/gen/stub.js': '// generated by the scaffold; do not edit\nexport const z = 3;\n',
    'src/notes.txt': 'not code',
  });
  assert.deepEqual(check(root, s), { 'src/none.js': ['no Source line'] });
});

test('the backlog reports old code until the branch touches it, and a file that now passes must leave it', () => {
  const root = project({ 'src/old.js': 'old\n', 'src/fixed.js': '// Source: REQ-1\n', 'factory/sources-backlog.txt': '# old\nsrc/old.js\nsrc/fixed.js\n' });
  const v = verdict(root, s);
  assert.deepEqual(v.reported, ['src/old.js: no Source line']);
  assert.deepEqual(v.red, ['src/fixed.js: passes now, remove it from factory/sources-backlog.txt']);
  assert.deepEqual(verdict(root, s, { touched: new Set(['src/old.js']) }).red[0], 'src/old.js: no Source line');
});

test('run whole: red, then the backlog written, then green', () => {
  const root = project({ 'src/old.js': 'old\n' });
  const run = (...a) => spawnSync(process.execPath, [path.join(here, 'sources.mjs'), ...a], { cwd: root, encoding: 'utf8' });
  let r = run();
  assert.equal(r.status, 1);
  assert.match(r.stderr, /src\/old\.js: no Source line/);
  assert.match(run('--write-backlog').stdout, /wrote 1 files/);
  r = run();
  assert.equal(r.status, 0);
  assert.match(r.stdout, /backlog, reported only: 1 problems[\s\S]*sources: green, 1 files/);
});
